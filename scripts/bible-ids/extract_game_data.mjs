#!/usr/bin/env node
// Archives every plain game-data table in a saved LOA-SIM chunk (the same file extract_tables.mjs
// reads, see README.md) as scripts/bible-ids/game-data.json. Nothing here is loaded by the site:
// it is the reference for decode work the importer does not do yet (items, weapons, bracers,
// engraving values, accessory rolls, honing, skills). Move a table into extract_tables.mjs when
// bible-decode.js starts reading it.
//   node scripts/bible-ids/extract_game_data.mjs path/to/chunk.js [--out file]
// The chunk's variable names are minified and change between builds. A name that is missing, or a
// table that no longer has the expected shape, makes the script fail instead of writing a gap.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const oi = argv.indexOf("--out");
const outPath = oi >= 0 ? argv[oi + 1] : path.join(here, "game-data.json");
const chunkPath = argv.find((a, i) => !a.startsWith("--") && argv[i - 1] !== "--out");
if (!chunkPath) { console.error("usage: extract_game_data.mjs chunk.js [--out file]"); process.exit(2); }
const s = fs.readFileSync(chunkPath, "utf8");

function balanced(src, i) {
  const open = src[i], close = open === "{" ? "}" : "]";
  let d = 0, q = null;
  for (let k = i; k < src.length; k++) {
    const c = src[k];
    if (q) { if (c === "\\") k++; else if (c === q) q = null; continue; }
    if (c === '"' || c === "'" || c === "`") { q = c; continue; }
    if (c === open) d++;
    else if (c === close) { d--; if (d === 0) return k + 1; }
  }
  throw new Error("unbalanced literal");
}
function literalAt(start) { return s.slice(start, balanced(s, start)); }
function literalNamed(name) {
  const m = new RegExp("[,;\\s]" + name + "=([{\\[])").exec(s);
  if (!m) throw new Error("table " + name + " not found in chunk");
  return literalAt(m.index + m[0].length - 1);
}
// The literal that starts `skip` characters into the first occurrence of `anchor`.
function literalAfter(anchor, skip = 0) {
  const i = s.indexOf(anchor);
  if (i < 0) throw new Error("anchor " + anchor + " not found in chunk");
  return literalAt(i + skip);
}
// ke(...) in the engraving value table turns percentages into basis points.
const ke = (...a) => a.map((t) => Math.round(t * 100));
const evalLit = (src) => new Function("ke", "return (" + src + ")")(ke);
const plain = (v) => JSON.parse(JSON.stringify(v));

const need = (cond, msg) => { if (!cond) throw new Error(msg); };
const nkeys = (o) => Object.keys(o).length;

const out = { _about: "Generated by scripts/bible-ids/extract_game_data.mjs from a saved LOA-SIM chunk. Reference only, not loaded by the site." };

// Loadout stats[] type ids (the names LOA-SIM gives them; 3/4/5 STR/DEX/INT and 7/8/9 their
// multipliers are not named there, see README.md).
out.statTypes = plain(evalLit(literalNamed("Ge")));
need(out.statTypes.BaseAttack === 1 && out.statTypes.ArkGridCore === 29, "statTypes changed shape");

// Every item id -> [icon, name, grade]. Ark Grid cores and astrogems are in here too.
out.itemNames = plain(evalLit(literalNamed("Oa")));
need(nkeys(out.itemNames) > 500, "itemNames has too few entries");

// Ark Grid astrogem cores: id -> { name, attr, willpower, options }.
out.astrogemCores = plain(evalLit(literalNamed("Aa")));
need(out.astrogemCores[1000]?.name === "Stability", "astrogemCores changed shape");

// Ark Grid core item id -> core name (id // 10), the same table extract_tables.mjs ships.
out.coreNames = plain(evalLit(literalNamed("M1")));
need(nkeys(out.coreNames) > 400, "coreNames has too few entries");

// Weapons: id -> { infusion, icon, name }; X0[infusion][honing] -> { ilvl, weaponPower }.
out.weaponNames = plain(evalLit(literalNamed("vr")));
out.weaponPowerByHoning = plain(evalLit(literalNamed("X0")));
need(nkeys(out.weaponNames) > 100 && out.weaponPowerByHoning.length === 4, "weapon tables changed shape");

// Bracer (KR preview slot "bracer" / "vambrace", item id 134xxxxxx). The grade is the digit at
// 10^5 minus 3 (0 epic, 1 legendary, 2 relic, 3 ancient); honing levels per grade are
// grade ranges below. bracerStatsByHoning[honing] = [mainStat, vitality, weaponPower, attackFlat];
// the attack power percent is the grade index.
out.bracerGrades = ["epic", "legendary", "relic", "ancient"];
out.bracerHoningRange = plain(evalLit(literalAfter("wa={epic:", 3)));
out.bracerStatsByHoning = plain(evalLit(literalNamed("ds")));
need(out.bracerStatsByHoning.length > 20 && out.bracerHoningRange.ancient[1] === 25, "bracer tables changed shape");

// Order unknown in LOA-SIM's own code; kept verbatim: rows [15,145000,14500,600,1800,30,22,5200].
out.unlabeledTableXl = plain(evalLit(literalNamed("xl")));

// Class main stat multipliers used by LOA-SIM's combat power estimate, by class key.
out.classStatFactor = plain(evalLit(literalNamed("vs")));

// Bracelet effects, attack (V0) and support (Ir) lists: { key "type:id", value, family, grade,
// text, t4, side? }. Parsed by regex because the entries mix literals and booleans (!0 / !1).
function bracelets(src) {
  const rows = [];
  for (const m of src.matchAll(/\{key:"(\d+):(\d+)",value:([\d.]+)(?:,side:"([^"]*)")?,family:"([^"]+)",grade:(\d),text:"((?:[^"\\]|\\.)*)",t4:(!0|!1)(?:,side:"([^"]*)")?\}/g)) {
    rows.push({ key: m[1] + ":" + m[2], value: +m[3], family: m[5], grade: +m[6], text: JSON.parse('"' + m[7] + '"'), t4: m[8] === "!0", side: m[4] ?? m[9] ?? null });
  }
  need(rows.length === (src.match(/\{key:"/g) || []).length, "a bracelet entry did not parse");
  return rows;
}
out.braceletsAttack = bracelets(literalNamed("V0"));
out.braceletsSupport = bracelets(literalNamed("Ir"));

// Accessory lines LOA-SIM scores (key, name, type and index of the loadout stat) and the
// accessory roll values by "type:index" (low / mid / high).
out.accessoryLines = [];
for (const src of [literalNamed("Yn"), literalNamed("Xn")]) {
  for (const m of src.matchAll(/\{key:"([^"]+)",name:"([^"]+)",match:a=>a\.type===(\d+)&&a\.index===(\d+),values:\{low:([\d.e]+),mid:([\d.e]+),high:([\d.e]+)\}/g)) {
    out.accessoryLines.push({ key: m[1], name: m[2], type: +m[3], index: +m[4], low: +m[5], mid: +m[6], high: +m[7] });
  }
}
need(out.accessoryLines.length >= 7, "accessoryLines has too few entries");
out.accessoryRolls = plain(evalLit(literalAfter('{"2:74":{name:')));
need(out.accessoryRolls["2:74"]?.values.length === 3, "accessoryRolls changed shape");

// Engravings: id -> name (class engravings), id -> [icon, name] (all), and the value tables.
out.engravingNamesClass = plain(evalLit(literalNamed("K1")));
out.engravingNamesAll = plain(evalLit(literalNamed("zn")));
out.engravingValues = plain(evalLit(literalNamed("Cr")));
need(nkeys(out.engravingValues) > 10, "engravingValues has too few entries");

// LOA-SIM's constants block: gem battle points, engraving, accessory, cores (id -> points).
out.constants = plain(evalLit(literalNamed("Ct")));
need(out.constants.gems?.T4?.length === 10, "constants changed shape");

// Gem id remap and astrogem option names, the same tables extract_tables.mjs ships.
out.gemRemap = plain(evalLit(literalNamed("w1")));
out.astrogemOptions = plain(evalLit(literalNamed("Ya")));
out.astrogemOptionsShort = plain(evalLit(literalNamed("Zr")));

// Honing and upgrade costs and tables (verbatim), materials, raids, skills.
out.honingByPart = plain(evalLit(literalNamed("ms")));
out.honingByPartSecond = plain(evalLit(literalNamed("fs")));
out.upgradeCosts = plain(evalLit(literalNamed("Dl")));
out.karma = plain(evalLit(literalNamed("wl")));
out.materials = plain(evalLit(literalNamed("Fr")));
out.raids = plain(evalLit(literalNamed("wd")));
out.skills = plain(evalLit(literalNamed("qa")));
out.skillsByClassGroup = plain(evalLit(literalNamed("y1")));
need(nkeys(out.skills) > 1000, "skills has too few entries");

const counts = Object.fromEntries(Object.entries(out).filter(([k]) => k !== "_about").map(([k, v]) => [k, Array.isArray(v) ? v.length : Object.keys(v).length]));
fs.writeFileSync(outPath, JSON.stringify(out) + "\n");
console.log("wrote", outPath, counts, fs.statSync(outPath).size, "bytes");
